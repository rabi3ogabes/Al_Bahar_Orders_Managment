#!/usr/bin/env python3
"""Writes the five heritage artworks (dhow, souq, dunes, museum, arabesque) in the forms the products need, from the drawings in
scenes.py, so they can never drift apart:

  backend/public/brand/qatar-<key>.svg           dashboard preview and reference copy
  storefront/src/assets/qatar-<key>.svg          web store (byte-identical copy)
  mobile/lib/core/theme/qatar_art_paths.dart     the app paints the same shapes natively (header carries one sha256 per artwork)

The Doha skyline itself is drawn by build.py (unchanged). Run from the repository root:  python3 scripts/qatar-skyline/build_scenes.py
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from art import fmt, svg  # noqa: E402
from scenes import SCENES  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]


def dart(built):
    out = ['// GENERATED by scripts/qatar-skyline/build_scenes.py from scripts/qatar-skyline/scenes.py. Do not edit by hand.']
    for key, (scene, digest) in built.items():
        out.append(f'// source-sha256 {key}: {digest}')
    out += ['', "import 'dart:ui';", '',
            '/// One built-in Qatar artwork: closed polygons (flat x, y lists) in a [width] x [height] box. Fill them non-zero: seams and windows are wound',
            '/// the other way. A [tile] artwork is one cell of a repeating pattern; the others are scenes that stand on the bottom edge.',
            'class QatarArtData {',
            '  const QatarArtData({required this.key, required this.width, required this.height, required this.tile, required this.shapes});',
            '',
            '  final String key;', '  final double width;', '  final double height;', '  final bool tile;', '  final List<List<double>> shapes;', '',
            '  Path toPath() {', '    final path = Path()..fillType = PathFillType.nonZero;', '    for (final s in shapes) {',
            '      path.moveTo(s[0], s[1]);', '      for (var i = 2; i + 1 < s.length; i += 2) {', '        path.lineTo(s[i], s[i + 1]);', '      }',
            '      path.close();', '    }', '    return path;', '  }', '}', '']
    names = []
    for key, (scene, digest) in built.items():
        name = f'_{key}'
        names.append((key, name))
        out.append(f'const {name} = QatarArtData(')
        out.append(f"  key: '{key}',")
        out.append(f'  width: {scene.width},')
        out.append(f'  height: {scene.height},')
        out.append(f'  tile: {"true" if scene.tile else "false"},')
        out.append('  shapes: [')
        for shape in scene.shapes:
            out.append('    [' + ', '.join(f'{fmt(x)}, {fmt(y)}' for x, y in shape) + '],')
        out.append('  ],')
        out.append(');')
        out.append('')
    out.append('/// Every built-in artwork except the Doha skyline (see qatar_skyline_paths.dart), by the key the server sends as `scene`.')
    out.append('const kQatarArt = <String, QatarArtData>{')
    for key, name in names:
        out.append(f"  '{key}': {name},")
    out.append('};')
    out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    built = {}
    for key, fn in SCENES.items():
        scene = fn()
        body = svg(scene)
        digest = hashlib.sha256(body.encode()).hexdigest()
        built[key] = (scene, digest)
        for target in (ROOT / f'backend/public/brand/qatar-{key}.svg', ROOT / f'storefront/src/assets/qatar-{key}.svg'):
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body)
        print(key, len(scene.shapes), 'shapes', digest[:12])
    target = ROOT / 'mobile/lib/core/theme/qatar_art_paths.dart'
    target.write_text(dart(built))
    print('wrote', target.relative_to(ROOT), target.stat().st_size, 'bytes')
