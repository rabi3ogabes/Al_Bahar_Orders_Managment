export const TEXT = { en, ar };

/** The dictionary for a language; `extra` (for example server-translated status names) wins over the built-in words. */
export function textFor(lang, extra = {}) {
    return { ...en, ...(lang === 'ar' ? ar : {}), ...extra };
}

/** "Order :n" with { n: 5 } to "Order 5". Unknown placeholders are kept. */
export function fmt(str, vars = {}) {
    return String(str ?? '').replace(/:(\w+)/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
}
